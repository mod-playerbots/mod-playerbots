"""Verify the committed SQL against its manifest and known rows."""

from __future__ import annotations

import hashlib
import json
import re
import unittest
from pathlib import Path

TOOL_DIR = Path(__file__).resolve().parents[1]
SQL_PATH = TOOL_DIR / "data" / "playerbots_quest_poi_z.sql"
MANIFEST_PATH = TOOL_DIR / "data" / "manifest.json"
ROW_RE = re.compile(
    r"\((\d+),(\d+),(\d+),(\d+),(-?\d+\.\d+),(\d+),(\d+),'([^']*)',([01]),'([^']*)'\)"
)


class SqlArtifactTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.manifest = json.loads(MANIFEST_PATH.read_text())
        cls.sql = SQL_PATH.read_text()
        cls.rows = ROW_RE.findall(cls.sql)

    def test_header(self) -> None:
        self.assertTrue(self.sql.startswith("-- playerbots_quest_poi_z"))
        self.assertIn("Generated by mod-playerbots/apps/quest_poi_z_baker/quest_poi_z_baker.py", self.sql)
        self.assertIn("CREATE TABLE IF NOT EXISTS `playerbots_quest_poi_z`", self.sql)

    def test_manifest_hashes(self) -> None:
        self.assertEqual(
            hashlib.sha256(SQL_PATH.read_bytes()).hexdigest(),
            self.manifest["sql_sha256"],
        )
        self.assertEqual(
            hashlib.sha256((TOOL_DIR / "quest_poi_z_baker.py").read_bytes()).hexdigest(),
            self.manifest["script_sha256"],
        )
        bundle = hashlib.sha256()
        paths = [TOOL_DIR / "quest_poi_z_baker.py", TOOL_DIR / "db.py"]
        paths += sorted((TOOL_DIR / "terrain").rglob("*.py"))
        for path in paths:
            bundle.update(path.read_bytes())
        self.assertEqual(bundle.hexdigest(), self.manifest["bundle_sha256"])

    def test_row_counts(self) -> None:
        self.assertEqual(len(self.rows), self.manifest["rows"])
        pairs = {(int(r[0]), int(r[1])) for r in self.rows}
        triples = {(int(r[0]), int(r[1]), int(r[2])) for r in self.rows}
        self.assertEqual(len(pairs), self.manifest["quest_poi_pairs"])
        self.assertEqual(len(triples), self.manifest["quest_poi_point_triples"])
        self.assertEqual(len({int(r[0]) for r in self.rows}), self.manifest["quests"])

    def test_row_ranges(self) -> None:
        for row in self.rows:
            rank = int(row[5])
            confidence = int(row[6])
            self.assertGreaterEqual(rank, 1)
            self.assertLessEqual(rank, 4)
            self.assertGreaterEqual(confidence, 0)
            self.assertLessEqual(confidence, 100)
            self.assertIn(row[8], ("0", "1"))

    def test_quest_62_trigger_candidates(self) -> None:
        q62 = [r for r in self.rows if int(r[0]) == 62]
        self.assertTrue(q62)
        rank1 = {(int(r[1]), int(r[2])): r for r in q62 if int(r[5]) == 1}
        self.assertIn((0, 0), rank1)
        self.assertEqual(rank1[(0, 0)][4], "4.48")
        self.assertEqual(rank1[(0, 0)][6], "93")
        self.assertIn("trigger", rank1[(0, 0)][7])
        self.assertIn("-9835.1,81.5,3.4", rank1[(0, 0)][9])
        self.assertIn((0, 4), rank1)
        self.assertIn((0, 5), rank1)


if __name__ == "__main__":
    unittest.main()
